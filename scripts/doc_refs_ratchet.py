BASELINE_VERSION = 1
DEFAULT_BASELINE = ".doc-refs-ratchet-baseline.json"
DEFAULT_INCLUDE = ("README.md", "CLAUDE.md", "docs/")
#: Always excluded, whatever the adopter's own `exclude` adds.
BUILTIN_EXCLUDES = ("**/node_modules/**", "**/.venv/**", "**/venv/**")
GENERATED_MARKERS = ("DO NOT EDIT", "@generated")  # case-sensitive: "Do NOT edit this file per-app" is prose
GENERATED_HEAD_LINES = 5
GIT_TIMEOUT_S = 120
#: A child name no repo tracks, asked of `git check-ignore` under each candidate folder.
_PROBE = ".doc-refs-probe"

EXIT_PASS, EXIT_RISE, EXIT_CONFIG, EXIT_NOT_CONFIRMED = 0, 1, 2, 3

# Vendor-verbatim module: derives the flag locally (the shared `src/no_window.py`
# would not resolve in a consumer tree), the documented exception.
_NO_WINDOW = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0

_CONFIG_KEYS = {"enabled", "baseline", "include", "exclude", "allow_refs", "retired", "trees"}
_RETIRED_KEYS = {"term", "why"}
#: A retired term matches only as a whole name: a longer word or kebab-case name containing it is another name.
_NAME_CHARS = r"\w-"
SKILL_FILE = "SKILL.md"
RETIRED_PREFIX = "retired:"

_FENCE_OPEN = re.compile(r"^[ \t>]*(?:(?:[-+*]|\d{1,9}[.)])[ \t]+)*(`{3,}|~{3,})(.*)$")
_FENCE_CLOSE = re.compile(r"^[ \t>]*(`{3,}|~{3,})[ \t]*$")
#: Info strings of a fence that can hold a layout tree; a `python` or `mermaid` fence never does.
_TREE_INFO = frozenset({"", "text", "txt", "tree", "plain", "plaintext"})
#: The two-dash connector is required: a one-dash `└─` is a DOM or flow diagram, not a file tree.
_TREE_ENTRY = re.compile(r"^(?P<lead>[ \t>│]*)[├└]── +(?P<rest>\S.*)$")
_TREE_LEAD = re.compile(r"^[ \t>│]*")
_TREE_NAME = re.compile(r"^[\w.@+-]+(?:/[\w.@+-]+)*/?$")
_HTML_TOKEN = re.compile(r"`+|<!--|-->")
_BACKTICKS = re.compile(r"`+")
_LINK_TARGET = re.compile(r"\]\(\s*(<[^>]*>|[^)\s]+)(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)")
_REF_DEFINITION = re.compile(r"^[ \t>]*\[[^\]]+\]:[ \t]*(<[^>]*>|\S+)")
_ATTRIBUTE = re.compile(r"""\b(?:href|src)\s*=\s*(?:"([^"]*)"|'([^']*)')""", re.IGNORECASE)
_LOOPBACK_PORT = re.compile(r"(?<![\w.])(?:localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\]):(\d{2,5})(?!\d)")
_BARE_PORT = re.compile(r":(\d{2,5})")
_SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")
_MODULE = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$")
#: A trailing line, symbol or test-id suffix is not part of the path:
#: `x.py:12`, `x.py:12-30`, `x.py#L12`, `x.py:func`, `x.py::test_y[param]`.
_LINE_SUFFIX = re.compile(r"(?:::.*|:\d+(?:[-:]\d+)?|:[A-Za-z_][\w.]*|#L\d+(?:-L?\d+)?)$")
#: Characters that mark a template, a glob, a variable or an argument, never a literal path.
_PLACEHOLDER = set("<>*?{}[]$%|=…")
#: A possessive, a pronoun or a repo slug right before a span hands it to another owner:
#: `fleet-config`'s `docs/x.md`, its `docs/x.md`, local-llm-hub `docs/x.md`, `| task-os | src/x.py |`.
_QUALIFIER = re.compile(r"(?:['’]s|\bits|\btheir|(?<![\w/.-])[a-z0-9]+(?:-[a-z0-9]+)+)\Z", re.IGNORECASE)
_QUALIFIER_TRIM = " \t>*_[(`+:|"
_TRIM = "\"'`,;()"


class ConfigError(RuntimeError):
    """The `[doc_refs_ratchet]` table or the baseline file is unusable."""


class NotConfirmed(RuntimeError):
    """A file could not be scanned or a reference could not be resolved."""


@dataclass(frozen=True)
class Retired:
    term: str
    why: str


@dataclass(frozen=True)
class Config:
    baseline: str
    include: tuple[str, ...]
    exclude: tuple[str, ...]
    allow_refs: tuple[str, ...]
    retired: tuple[Retired, ...] = ()
    trees: bool = False


@dataclass(frozen=True)
class Ref:
    line: int
    kind: str  # "path", "link", "tree", "module", "port" or "retired"
    key: str  # what is resolved and recorded: a repo-relative path, `-m <module>`, `:<port>` or `retired:<term>`
    text: str  # the line it sits on, for messages
    why: str = ""  # a retired term's replacement, printed with the hit


@dataclass(frozen=True)
class Tree:
    """What a reference can resolve to: tracked files and their folders, plus the app's port."""

    files: frozenset[str]
    dirs: frozenset[str]
    top_dirs: frozenset[str]
    port: int | None


# ----------------------------------------------------------------- config

def _str_list(table: dict[str, object], name: str, default: tuple[str, ...]) -> tuple[str, ...]:
    if name not in table:
        return default
    value = table[name]
    if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
        raise ConfigError(f"[doc_refs_ratchet] {name} must be a list of non-empty strings")
    return tuple(value)


def _retired_list(table: dict[str, object]) -> tuple[Retired, ...]:
    value = table.get("retired", [])
    if not isinstance(value, list):
        raise ConfigError("[doc_refs_ratchet] retired must be a list of { term, why } tables")
    out: list[Retired] = []
    for item in value:
        if not isinstance(item, dict):
            raise ConfigError(f"[doc_refs_ratchet] retired entry {item!r} must be a {{ term, why }} table")
        unknown = sorted(set(item) - _RETIRED_KEYS)
        if unknown:
            raise ConfigError(f"[doc_refs_ratchet] retired entry: unknown key(s) {', '.join(unknown)}")
        term, why = item.get("term"), item.get("why")
        if not isinstance(term, str) or not term.strip():
            raise ConfigError(f"[doc_refs_ratchet] retired entry {item!r} needs a non-empty `term`")
        if not isinstance(why, str) or not why.strip():
            raise ConfigError(f"[doc_refs_ratchet] retired term {term!r} needs a non-empty `why` (what to use instead)")
        if any(r.term == term for r in out):
            raise ConfigError(f"[doc_refs_ratchet] retired term {term!r} is listed twice")
        out.append(Retired(term, why))
    return tuple(out)


def parse_config(toml_text: str) -> Config | None:
    """`[doc_refs_ratchet]` -> `Config`, or None when the stage is not enabled.

    An absent table, or `enabled = false`, is the one correct skip: the adopter
    declared it. Anything malformed raises `ConfigError` -- a typo'd key must not
    quietly run with defaults.
    """
    table = tomllib.loads(toml_text).get("doc_refs_ratchet")
    if table is None:
        return None
    if not isinstance(table, dict):
        raise ConfigError("[doc_refs_ratchet] must be a table")
    unknown = sorted(set(table) - _CONFIG_KEYS)
    if unknown:
        raise ConfigError(f"[doc_refs_ratchet]: unknown key(s) {', '.join(unknown)}")
    enabled = table.get("enabled", False)
    if not isinstance(enabled, bool):
        raise ConfigError("[doc_refs_ratchet] enabled must be true or false")
    if not enabled:
        return None
    baseline = table.get("baseline", DEFAULT_BASELINE)
    if not isinstance(baseline, str) or not baseline:
        raise ConfigError("[doc_refs_ratchet] baseline must be a non-empty string")
    trees = table.get("trees", False)
    if not isinstance(trees, bool):
        raise ConfigError("[doc_refs_ratchet] trees must be true or false")
    return Config(
        baseline,
        _str_list(table, "include", DEFAULT_INCLUDE),
        _str_list(table, "exclude", ()),
        _str_list(table, "allow_refs", ()),
        _retired_list(table),
        trees,
    )


def declared_port(toml_text: str) -> int | None:
    """The app's own `port` from `.fleet.toml` (`8447` or `":8447"`), or None when it declares none."""
    value = tomllib.loads(toml_text).get("port")
    if value is None:
        return None
    if isinstance(value, int) and not isinstance(value, bool) and 0 < value < 65536:
        return value
    if isinstance(value, str) and re.fullmatch(r":?\d{1,5}", value.strip()) and 0 < int(value.strip(":")) < 65536:
        return int(value.strip(":"))
    raise ConfigError(f".fleet.toml port must be a port number or \":<port>\", not {value!r}")


def vendored_dests(toml_text: str) -> tuple[str, ...]:
    """Every `dest` in the adopter's own `[vendored]` table (files or folders)."""
    table = tomllib.loads(toml_text).get("vendored")
    if not isinstance(table, dict):
        return ()
    dests = []
    for entry in table.values():
        dest = entry.get("dest") if isinstance(entry, dict) else None
        if isinstance(dest, str) and dest.strip("/"):
            dests.append(dest.replace("\\", "/").strip("/"))
    return tuple(sorted(dests))


def load_config(root: Path) -> tuple[Config | None, tuple[str, ...], int | None]:
    """(config or None when not enabled, vendored dests, declared port)."""
    path = root / ".fleet.toml"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    try:
        return parse_config(text), vendored_dests(text), declared_port(text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path} is not valid TOML: {exc}") from exc


