import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from collections import Counter
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from urllib.parse import unquote

REPO_ROOT = Path(__file__).resolve().parent.parent

BASELINE_VERSION = 1
DEFAULT_BASELINE = ".doc-refs-ratchet-baseline.json"
DEFAULT_INCLUDE = ("README.md", "CLAUDE.md", "docs/")
#: Always excluded, whatever the adopter's own `exclude` adds.
BUILTIN_EXCLUDES = ("**/node_modules/**", "**/.venv/**", "**/venv/**")
GENERATED_MARKERS = ("DO NOT EDIT", "@generated")  # case-sensitive: "Do NOT edit this file per-app" is prose
GENERATED_HEAD_LINES = 5
GIT_TIMEOUT_S = 120
#: A child name no repo tracks, asked of `git check-ignore` under each candidate folder.
_PROBE = ".doc-refs-probe"

EXIT_PASS, EXIT_RISE, EXIT_CONFIG, EXIT_NOT_CONFIRMED = 0, 1, 2, 3

# Vendor-verbatim module: derives the flag locally (the shared `src/no_window.py`
# would not resolve in a consumer tree), the documented exception.
_NO_WINDOW = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0

_CONFIG_KEYS = {"enabled", "baseline", "include", "exclude", "allow_refs"}

_FENCE_OPEN = re.compile(r"^[ \t>]*(?:(?:[-+*]|\d{1,9}[.)])[ \t]+)*(`{3,}|~{3,})(.*)$")
_FENCE_CLOSE = re.compile(r"^[ \t>]*(`{3,}|~{3,})[ \t]*$")
_HTML_TOKEN = re.compile(r"`+|<!--|-->")
_BACKTICKS = re.compile(r"`+")
_LINK_TARGET = re.compile(r"\]\(\s*(<[^>]*>|[^)\s]+)(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)")
_REF_DEFINITION = re.compile(r"^[ \t>]*\[[^\]]+\]:[ \t]*(<[^>]*>|\S+)")
_ATTRIBUTE = re.compile(r"""\b(?:href|src)\s*=\s*(?:"([^"]*)"|'([^']*)')""", re.IGNORECASE)
_LOOPBACK_PORT = re.compile(r"(?<![\w.])(?:localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\]):(\d{2,5})(?!\d)")
_BARE_PORT = re.compile(r":(\d{2,5})")
_SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")
_MODULE = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$")
#: A trailing line, symbol or test-id suffix is not part of the path:
#: `x.py:12`, `x.py:12-30`, `x.py#L12`, `x.py:func`, `x.py::test_y[param]`.
_LINE_SUFFIX = re.compile(r"(?:::.*|:\d+(?:[-:]\d+)?|:[A-Za-z_][\w.]*|#L\d+(?:-L?\d+)?)$")
#: Characters that mark a template, a glob, a variable or an argument, never a literal path.
_PLACEHOLDER = set("<>*?{}[]$%|=…")
#: A possessive, a pronoun or a repo slug right before a span hands it to another owner:
#: `fleet-config`'s `docs/x.md`, its `docs/x.md`, local-llm-hub `docs/x.md`, `| task-os | src/x.py |`.
_QUALIFIER = re.compile(r"(?:['’]s|\bits|\btheir|(?<![\w/.-])[a-z0-9]+(?:-[a-z0-9]+)+)\Z", re.IGNORECASE)
_QUALIFIER_TRIM = " \t>*_[(`+:|"
_TRIM = "\"'`,;()"


class ConfigError(RuntimeError):
    """The `[doc_refs_ratchet]` table or the baseline file is unusable."""


class NotConfirmed(RuntimeError):
    """A file could not be scanned or a reference could not be resolved."""


@dataclass(frozen=True)
class Config:
    baseline: str
    include: tuple[str, ...]
    exclude: tuple[str, ...]
    allow_refs: tuple[str, ...]


@dataclass(frozen=True)
class Ref:
    line: int
    kind: str  # "path", "link", "module" or "port"
    key: str  # what is resolved and recorded: a repo-relative path, `-m <module>` or `:<port>`
    text: str  # the line it sits on, for messages


@dataclass(frozen=True)
class Tree:
    """What a reference can resolve to: tracked files and their folders, plus the app's port."""

    files: frozenset[str]
    dirs: frozenset[str]
    top_dirs: frozenset[str]
    port: int | None


# ----------------------------------------------------------------- config

def _str_list(table: dict[str, object], name: str, default: tuple[str, ...]) -> tuple[str, ...]:
    if name not in table:
        return default
    value = table[name]
    if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
        raise ConfigError(f"[doc_refs_ratchet] {name} must be a list of non-empty strings")
    return tuple(value)


def parse_config(toml_text: str) -> Config | None:
    """`[doc_refs_ratchet]` -> `Config`, or None when the stage is not enabled.

    An absent table, or `enabled = false`, is the one correct skip: the adopter
    declared it. Anything malformed raises `ConfigError` -- a typo'd key must not
    quietly run with defaults.
    """
    table = tomllib.loads(toml_text).get("doc_refs_ratchet")
    if table is None:
        return None
    if not isinstance(table, dict):
        raise ConfigError("[doc_refs_ratchet] must be a table")
    unknown = sorted(set(table) - _CONFIG_KEYS)
    if unknown:
        raise ConfigError(f"[doc_refs_ratchet]: unknown key(s) {', '.join(unknown)}")
    enabled = table.get("enabled", False)
    if not isinstance(enabled, bool):
        raise ConfigError("[doc_refs_ratchet] enabled must be true or false")
    if not enabled:
        return None
    baseline = table.get("baseline", DEFAULT_BASELINE)
    if not isinstance(baseline, str) or not baseline:
        raise ConfigError("[doc_refs_ratchet] baseline must be a non-empty string")
    return Config(
        baseline,
        _str_list(table, "include", DEFAULT_INCLUDE),
        _str_list(table, "exclude", ()),
        _str_list(table, "allow_refs", ()),
    )


def declared_port(toml_text: str) -> int | None:
    """The app's own `port` from `.fleet.toml` (`8447` or `":8447"`), or None when it declares none."""
    value = tomllib.loads(toml_text).get("port")
    if value is None:
        return None
    if isinstance(value, int) and not isinstance(value, bool) and 0 < value < 65536:
        return value
    if isinstance(value, str) and re.fullmatch(r":?\d{1,5}", value.strip()) and 0 < int(value.strip(":")) < 65536:
        return int(value.strip(":"))
    raise ConfigError(f".fleet.toml port must be a port number or \":<port>\", not {value!r}")


def vendored_dests(toml_text: str) -> tuple[str, ...]:
    """Every `dest` in the adopter's own `[vendored]` table (files or folders)."""
    table = tomllib.loads(toml_text).get("vendored")
    if not isinstance(table, dict):
        return ()
    dests = []
    for entry in table.values():
        dest = entry.get("dest") if isinstance(entry, dict) else None
        if isinstance(dest, str) and dest.strip("/"):
            dests.append(dest.replace("\\", "/").strip("/"))
    return tuple(sorted(dests))


def load_config(root: Path) -> tuple[Config | None, tuple[str, ...], int | None]:
    """(config or None when not enabled, vendored dests, declared port)."""
    path = root / ".fleet.toml"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    try:
        return parse_config(text), vendored_dests(text), declared_port(text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path} is not valid TOML: {exc}") from exc


# ------------------------------------------------------------------- globs

def _glob_regex(glob: str) -> re.Pattern[str]:
    """Repo-root-anchored glob -> regex; `**/` is zero or more directories."""
    out: list[str] = []
    i = 0
    while i < len(glob):
        if glob.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif glob.startswith("**", i):
            out.append(".*")
            i += 2
        elif glob[i] == "*":
            out.append("[^/]*")
            i += 1
        elif glob[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(glob[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


def matches_any(text: str, globs: tuple[str, ...]) -> bool:
    return any(_glob_regex(g).match(text) for g in globs)


def _under(path: str, prefix: str) -> bool:
    prefix = prefix.replace("\\", "/").strip("/")
    return path == prefix or path.startswith(prefix + "/")


def in_scope(path: str, cfg: Config, vendored: tuple[str, ...]) -> bool:
    """Is `path` a Markdown file this stage reads?"""
    if PurePosixPath(path).suffix.lower() != ".md":
        return False
    if not any(_under(path, p) for p in cfg.include):
        return False
    if any(_under(path, d) for d in vendored):
        return False
    return not matches_any(path, BUILTIN_EXCLUDES + cfg.exclude)


def is_generated(text: str) -> bool:
    head = "\n".join(text.split("\n", GENERATED_HEAD_LINES)[:GENERATED_HEAD_LINES])
    return any(marker in head for marker in GENERATED_MARKERS)


# -------------------------------------------------------------- extraction

def _blank_html_comments(line: str, in_comment: bool) -> tuple[str, bool]:
    """Drop `<!-- -->` text from one line; return (rest, still inside a comment).

    A `<!--` inside an inline code span is code, not a comment opener, so backtick
    runs are tracked on the way (a run closes the span opened by one of equal length).
    """
    kept: list[str] = []
    pos = 0
    code_len: int | None = None
    for m in _HTML_TOKEN.finditer(line):
        tok = m.group()
        if in_comment:
            if tok == "-->":
                in_comment = False
                pos = m.end()
        elif tok[0] == "`":
            if code_len is None:
                code_len = len(tok)
            elif code_len == len(tok):
                code_len = None
        elif tok == "<!--" and code_len is None:
            kept.append(line[pos:m.start()])
            in_comment = True
    if not in_comment:
        kept.append(line[pos:])
    return "".join(kept), in_comment


def split_code_spans(line: str) -> tuple[list[tuple[int, str]], str]:
    """((offset, content) of each inline code span, the line with those spans blanked).

    A span opens on a backtick run and closes on the next run of the same length;
    an unmatched run is literal text. Spans do not continue onto the next line.
    """
    spans: list[tuple[int, str]] = []
    rest: list[str] = []
    pos = 0
    runs = list(_BACKTICKS.finditer(line))
    i = 0
    while i < len(runs):
        opener = runs[i]
        close = next((j for j in range(i + 1, len(runs)) if len(runs[j].group()) == len(opener.group())), None)
        if close is None:
            i += 1
            continue
        rest.append(line[pos:opener.start()])
        spans.append((opener.start(), line[opener.end():runs[close].start()]))
        pos = runs[close].end()
        rest.append(" ")
        i = close + 1
    rest.append(line[pos:])
    return spans, "".join(rest)


def _clean_token(token: str) -> str:
    token = token.strip(_TRIM).replace("\\", "/")
    token = token.lstrip("&").strip(_TRIM)
    while token.startswith("./"):
        token = token[2:]
    return _LINE_SUFFIX.sub("", token)


def _is_literal_path(token: str) -> bool:
    if not token or any(c in _PLACEHOLDER for c in token) or "://" in token or "..." in token:
        return False
    if token.startswith(("/", "~", "-", "@")) or re.match(r"^[A-Za-z]:", token):
        return False
    return ".." not in token.split("/")


def _code_refs(span: str, top_dirs: frozenset[str], root_py: frozenset[str]) -> list[tuple[str, str]]:
    """(kind, key) for every path or `-m` module named in one inline code span."""
    found: list[tuple[str, str]] = []
    tokens = span.split()
    for i, raw in enumerate(tokens):
        if i and tokens[i - 1] == "-m":
            module = raw.strip(_TRIM)
            if _MODULE.match(module) and (module.split(".")[0] in top_dirs or module.split(".")[0] in root_py):
                found.append(("module", f"-m {module}"))
            continue
        token = _clean_token(raw)
        if not _is_literal_path(token):
            continue
        if "/" in token and token.split("/")[0] in top_dirs:
            found.append(("path", token.rstrip("/")))
    return found


def _link_key(target: str, doc_dir: str) -> str | None:
    """A link target as a repo-relative path, or None when it is not a local file reference."""
    target = target.strip().strip("<>").strip()
    if not target or target.startswith("#") or _SCHEME.match(target) or target.startswith("//"):
        return None
    target = unquote(target.split("#", 1)[0].split("?", 1)[0]).replace("\\", "/")
    if not target or any(c in _PLACEHOLDER for c in target):
        return None
    parts = [] if target.startswith("/") else [p for p in doc_dir.split("/") if p]
    for part in target.split("/"):
        if part in ("", "."):
            continue
        if part == "..":
            if not parts:
                return None  # leaves the repo: another checkout's tree, not checked
            parts.pop()
        else:
            parts.append(part)
    return "/".join(parts) or None


def _is_qualified(before: str, prev_tail: str) -> bool:
    """Does the text before a span name another owner (`fleet-config`'s, the scaffold's, its)?

    A span that opens its line reads the previous line's end, so a possessive
    wrapped onto the line above still counts.
    """
    if not before.strip(_QUALIFIER_TRIM):
        before = prev_tail + " " + before
    return bool(_QUALIFIER.search(before.rstrip(_QUALIFIER_TRIM)))


def _port_refs(spans: list[str], prose: str) -> list[int]:
    ports = [int(m.group(1)) for text in [*spans, prose] for m in _LOOPBACK_PORT.finditer(text)]
    ports += [int(span.strip()[1:]) for span in spans if _BARE_PORT.fullmatch(span.strip())]
    return ports


def scan_text(text: str, doc_path: str, top_dirs: frozenset[str], root_py: frozenset[str] = frozenset(),
              check_ports: bool = True) -> list[Ref]:
    """Every reference in one Markdown file; raises `NotConfirmed` on an unclosed block."""
    refs: list[Ref] = []
    parent = str(PurePosixPath(doc_path).parent)
    doc_dir = "" if parent == "." else parent
    fence: tuple[str, int, int] | None = None  # (fence char, run length, line it opened on)
    comment_opened: int | None = None
    prev_tail = ""
    for no, raw in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        if fence:
            close = _FENCE_CLOSE.match(raw)
            if close and close.group(1)[0] == fence[0] and len(close.group(1)) >= fence[1]:
                fence = None
            continue
        if comment_opened is None:
            opener = _FENCE_OPEN.match(raw)
            if opener and not (opener.group(1)[0] == "`" and "`" in opener.group(2)):
                fence = (opener.group(1)[0], len(opener.group(1)), no)
                continue
        line, inside = _blank_html_comments(raw, comment_opened is not None)
        if inside and comment_opened is None:
            comment_opened = no
        elif not inside:
            comment_opened = None
        located, prose = split_code_spans(line)
        spans = [span for _, span in located]
        context = raw.strip()
        for start, span in located:
            if not _is_qualified(line[:start], prev_tail):
                refs.extend(Ref(no, kind, key, context) for kind, key in _code_refs(span, top_dirs, root_py))
        prev_tail = line[-60:] if line.strip() else ""
        targets = [m.group(1) for m in _LINK_TARGET.finditer(prose)]
        definition = _REF_DEFINITION.match(prose)
        if definition:
            targets.append(definition.group(1))
        targets += [m.group(1) or m.group(2) or "" for m in _ATTRIBUTE.finditer(prose)]
        for target in targets:
            key = _link_key(target, doc_dir)
            if key:
                refs.append(Ref(no, "link", key, context))
        if check_ports:
            refs.extend(Ref(no, "port", f":{port}", context) for port in _port_refs(spans, prose))
    if fence:
        raise NotConfirmed(f"the fenced block opened on line {fence[2]} never closes")
    if comment_opened is not None:
        raise NotConfirmed(f"the HTML comment opened on line {comment_opened} never closes")
    return refs


# ------------------------------------------------------------------ resolve

def _git(root: Path, args: list[str], stdin: bytes | None = None) -> subprocess.CompletedProcess[bytes]:
    env = dict(os.environ, GIT_OPTIONAL_LOCKS="0")  # a read-only sweep must not leave index locks
    try:
        return subprocess.run(
            ["git", *args], cwd=root, capture_output=True, env=env, input=stdin,
            stdin=None if stdin is not None else subprocess.DEVNULL,
            creationflags=_NO_WINDOW, timeout=GIT_TIMEOUT_S, check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise NotConfirmed(f"git {args[0]} timed out after {GIT_TIMEOUT_S}s") from exc
    except OSError as exc:
        raise NotConfirmed(f"git could not start: {exc}") from exc


def _git_failed(args: list[str], proc: subprocess.CompletedProcess[bytes]) -> NotConfirmed:
    detail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
    return NotConfirmed(f"git {' '.join(args)} exited {proc.returncode}: {detail[-1] if detail else '(no output)'}")


def tracked_files(root: Path) -> list[str]:
    """Repo-relative, forward-slash paths of every tracked or untracked-but-not-ignored file."""
    args = ["ls-files", "-z", "--cached", "--others", "--exclude-standard"]
    proc = _git(root, args)
    if proc.returncode != 0:
        raise _git_failed(args, proc)
    return sorted(p for p in proc.stdout.decode("utf-8", "replace").split("\0") if p)


def ignored(root: Path, paths: list[str]) -> set[str]:
    """The subset of `paths` git ignores (machine-local by design, so never dangling)."""
    if not paths:
        return set()
    args = ["check-ignore", "--no-index", "-z", "--stdin"]
    proc = _git(root, args, "\0".join(paths).encode("utf-8") + b"\0")
    if proc.returncode not in (0, 1):  # 1 = none of them is ignored
        raise _git_failed(args, proc)
    return {p for p in proc.stdout.decode("utf-8", "replace").split("\0") if p}


def build_tree(files: list[str], port: int | None) -> Tree:
    dirs = {str(parent) for f in files for parent in PurePosixPath(f).parents if str(parent) != "."}
    return Tree(frozenset(files), frozenset(dirs), frozenset(d for d in dirs if "/" not in d), port)


def resolves(ref: Ref, tree: Tree) -> bool:
    if ref.kind == "port":
        return tree.port is None or ref.key == f":{tree.port}"
    if ref.kind == "module":
        base = ref.key[3:].replace(".", "/")
        return f"{base}.py" in tree.files or f"{base}/__init__.py" in tree.files or f"{base}/__main__.py" in tree.files
    if ref.key in tree.files or ref.key in tree.dirs:
        return True
    if ref.kind != "path":
        return False
    # `scripts/tool` is shorthand for `scripts/tool.py`; `src/pkg/mod.func` names a symbol in `src/pkg/mod.py`.
    module, dot, _ = ref.key.rpartition(".")
    if f"{ref.key}.py" in tree.files:
        return True
    return bool(dot) and "/" in module and (f"{module}.py" in tree.files or f"{module}/__init__.py" in tree.files)


def dangling_tree(root: Path, cfg: Config, vendored: tuple[str, ...], port: int | None) -> dict[str, list[Ref]]:
    """Dangling, non-allowed references per in-scope file (only files with at least one)."""
    files = tracked_files(root)
    tree = build_tree(files, port)
    root_py = frozenset(f[:-3] for f in files if "/" not in f and f.endswith(".py"))
    candidates: dict[str, list[Ref]] = {}
    for path in files:
        if not in_scope(path, cfg, vendored):
            continue
        try:
            raw = (root / path).read_bytes()
        except FileNotFoundError:
            continue  # tracked but deleted in the working tree: nothing to read
        except OSError as exc:
            raise NotConfirmed(f"{path}: cannot be read: {exc}") from exc
        try:
            text = raw.decode("utf-8-sig")
        except UnicodeDecodeError as exc:
            raise NotConfirmed(f"{path}: is not valid UTF-8: {exc}") from exc
        if is_generated(text):
            continue
        try:
            refs = scan_text(text, path, tree.top_dirs, root_py, check_ports=port is not None)
        except NotConfirmed as exc:
            raise NotConfirmed(f"{path}: {exc}") from exc
        bad = [r for r in refs if not resolves(r, tree) and not matches_any(r.key, cfg.allow_refs)]
        if bad:
            candidates[path] = bad
    keys = sorted({r.key for refs in candidates.values() for r in refs if r.kind in ("path", "link")})
    # The probe child catches a folder whose contents are ignored (`certs/*`) but not the folder itself.
    hits = ignored(root, [k for key in keys for k in (key, f"{key}/{_PROBE}")])
    local = {k.removesuffix(f"/{_PROBE}") for k in hits}
    found = {}
    for path, refs in candidates.items():
        kept = [r for r in refs if r.key not in local]
        if kept:
            found[path] = kept
    return found


# ---------------------------------------------------------------- baseline

def current_entries(found: dict[str, list[Ref]]) -> dict[str, Counter[str]]:
    return {path: Counter(r.key for r in refs) for path, refs in found.items()}


def read_baseline(path: Path) -> dict[str, Counter[str]]:
    """Baseline file -> ``{doc path: Counter(reference)}``. Raises `ConfigError` on anything off."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise ConfigError(f"cannot read baseline {path}: {exc}") from exc
    except ValueError as exc:
        raise ConfigError(f"baseline {path} is not valid JSON: {exc}") from exc
    if not isinstance(data, dict) or data.get("version") != BASELINE_VERSION:
        raise ConfigError(f"baseline {path}: expected an object with version {BASELINE_VERSION}")
    raw_entries = data.get("entries")
    if not isinstance(raw_entries, list):
        raise ConfigError(f"baseline {path}: `entries` must be a list")
    out: dict[str, Counter[str]] = {}
    for item in raw_entries:
        if not isinstance(item, dict) or not isinstance(item.get("key"), str):
            raise ConfigError(f"baseline {path}: malformed entry {item!r}")
        refs = item.get("refs")
        if not isinstance(refs, list) or not refs or not all(isinstance(r, str) and r for r in refs):
            raise ConfigError(f"baseline {path}: entry {item!r} needs a non-empty `refs` list of strings")
        out[item["key"]] = Counter(refs)
    return out


def render_baseline(entries: dict[str, Counter[str]]) -> str:
    """Sorted, one file per line, no line numbers, so a baseline diff reviews cleanly."""
    lines = []
    for key in sorted(entries):
        record = {"key": key, "refs": sorted(entries[key].elements())}
        lines.append("    " + json.dumps(record, ensure_ascii=False))
    body = "[\n" + ",\n".join(lines) + "\n  ]" if lines else "[]"
    return f'{{\n  "version": {BASELINE_VERSION},\n  "entries": {body}\n}}\n'


def diff(current: dict[str, Counter[str]], baseline: dict[str, Counter[str]]) -> tuple[dict[str, Counter[str]], int]:
    """(per file, the references beyond the baseline; how many baselined references are gone)."""
    added: dict[str, Counter[str]] = {}
    gone = 0
    for path in sorted(set(current) | set(baseline)):
        cur, base = current.get(path, Counter()), baseline.get(path, Counter())
        extra = cur - base
        if extra:
            added[path] = extra
        gone += sum((base - cur).values())
    return added, gone


# -------------------------------------------------------------------- CLI

def _total(entries: dict[str, Counter[str]]) -> int:
    return sum(sum(c.values()) for c in entries.values())


def _report_added(added: dict[str, Counter[str]], found: dict[str, list[Ref]]) -> None:
    print(f"doc refs ratchet: {_total(added)} dangling reference(s) not in the baseline, in {len(added)} file(s):")
    for path, extra in added.items():
        for ref in found[path]:
            if extra[ref.key] > 0:
                extra[ref.key] -= 1
                print(f"  {path}:{ref.line}: {ref.kind} `{ref.key}` does not exist  | {ref.text[:140]}")


def run(root: Path, *, init: bool, update: bool, allow_additions: bool) -> int:
    try:
        cfg, vendored, port = load_config(root)
    except ConfigError as exc:
        print(f"doc refs ratchet: CONFIG ERROR: {exc}")
        return EXIT_CONFIG
    if cfg is None:
        if init or update:
            print("doc refs ratchet: not enabled -- set [doc_refs_ratchet] enabled = true in .fleet.toml first")
            return EXIT_CONFIG
        print("doc refs ratchet: not enabled (no [doc_refs_ratchet] enabled = true in .fleet.toml)")
        return EXIT_PASS
    baseline_path = root / cfg.baseline

    baseline: dict[str, Counter[str]] = {}
    if init:
        if baseline_path.exists():
            print(f"doc refs ratchet: {cfg.baseline} already exists; --init never overwrites it")
            return EXIT_CONFIG
    elif baseline_path.is_file():
        try:
            baseline = read_baseline(baseline_path)
        except ConfigError as exc:
            print(f"doc refs ratchet: BASELINE ERROR: {exc}")
            return EXIT_CONFIG
    else:
        print(f"doc refs ratchet: FAIL: baseline {cfg.baseline} is missing -- "
              "run `python scripts/doc_refs_ratchet.py --init`")
        return EXIT_RISE

    try:
        found = dangling_tree(root, cfg, vendored, port)
    except NotConfirmed as exc:
        print(f"doc refs ratchet: NOT CONFIRMED: {exc}")
        print("  (the references could not be resolved, so this is neither a pass nor a clean tree)")
        return EXIT_NOT_CONFIRMED
    current = current_entries(found)

    if init:
        baseline_path.write_text(render_baseline(current), encoding="utf-8", newline="\n")
        print(f"doc refs ratchet: wrote {cfg.baseline} with {_total(current)} dangling reference(s) "
              f"in {len(current)} file(s)")
        return EXIT_PASS

    added, gone = diff(current, baseline)
    if update:
        if added and not allow_additions:
            _report_added(added, found)
            print("doc refs ratchet: nothing written -- fix the references, or raise the baseline with --allow-additions")
            return EXIT_RISE
        baseline_path.write_text(render_baseline(current), encoding="utf-8", newline="\n")
        print(f"doc refs ratchet: {cfg.baseline} now has {_total(current)} reference(s) in {len(current)} file(s) "
              f"({gone} dropped, {_total(added)} added)")
        return EXIT_PASS

    if added:
        _report_added(added, found)
        print("  Point the reference at what exists now, or drop it. An intentional pointer (another repo's path, "
              "a file an adopter creates) goes in [doc_refs_ratchet] allow_refs; or (reviewed) raise the baseline "
              "with `--update-baseline --allow-additions`.")
        return EXIT_RISE
    ports = f"; port :{port}" if port is not None else "; no port declared, ports unchecked"
    print(f"doc refs ratchet: PASS ({_total(current)} baselined dangling reference(s) in {len(current)} file(s), "
          f"none new{ports})")
    if gone:
        print(f"  {gone} baselined reference(s) now resolve or are gone -- run "
              "`python scripts/doc_refs_ratchet.py --update-baseline` to lower it")
    return EXIT_PASS


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repo root (default: this repo)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--init", action="store_true", help="write the first baseline; never overwrites")
    mode.add_argument("--update-baseline", action="store_true", help="drop references that resolve (shrink only)")
    parser.add_argument("--allow-additions", action="store_true",
                        help="with --update-baseline: also add references (shows in review)")
    args = parser.parse_args(argv)
    if args.allow_additions and not args.update_baseline:
        parser.error("--allow-additions only applies with --update-baseline")
    return run(args.root.resolve(), init=args.init, update=args.update_baseline,
               allow_additions=args.allow_additions)


if __name__ == "__main__":
    sys.exit(main())
