"""Ratchet on README size and history markers in Markdown docs.

The README is the first file every agent reads, so its size is a per-session
cost; and the story of how a doc got here ("added in #123", a dated walk log, a
changelog section) goes stale while git, the PRs and the issues already hold it.
A doc states what is true and why, in the present tense. This stage enforces
that structurally, per file, against a committed baseline: it fails only when a
count *rises*. Existing debt never blocks work, but it cannot grow. Convention:
docs/readme-and-docs.md.

Two measures, both per file:

  * README size, in bytes (CRLF normalised to LF, so a Windows checkout and CI
    agree). A root `README.md` at or under `readme_max_bytes` needs no entry and
    must stay under it. One over budget is baselined at today's size and may only
    shrink; a new over-budget README fails by name. Lines are not measured.
  * History markers in the root `README.md` and `docs/**/*.md`, one integer per
    file, the sum of:
      - issue references: `#` plus one to five digits (`#123`, `repo#123`,
        `owner/repo#123`), not preceded by `&`, `#` or `/` and not followed by a
        word character or `-`. A reference inside inline code counts: a
        backtick is not a way around the rule.
      - dated headings: an ATX heading line holding an ISO date (`2026-06-24`).
      - changelog headings: a heading that opens with `Changelog`, `Release
        notes`, `Release history` or `What's new`.

Not counted: fenced code blocks (backtick and tilde; the closing fence is at
least as long as the opener), HTML comments, bare URLs and autolinks, link and
image targets, reference-definition URLs, `href`/`src` attribute values and
`&#123;` entities. `[#9](https://.../9)` therefore counts once, through its text.
Indented code blocks are not detected (they cannot be told from list
continuation); prose dates are legal, because expiry and rotation dates belong in
the README.

Opt-in, per adopter, in its own `.fleet.toml` -- re-vendoring never breaks a
repo that has not opted in:

    [docs_ratchet]
    enabled         = true
    baseline        = ".docs-ratchet-baseline.json"   # default
    include         = ["README.md", "docs/"]           # path prefixes; the default
    exclude         = ["docs/reports/**"]              # globs, e.g. generated per-run reports
    readme_max_bytes = 40960                           # default: 40 KiB
    allow_refs      = ["owner/repo#178"]               # exact text as written; default none

Scope is `git ls-files --cached --others --exclude-standard` minus files whose first lines say `DO NOT EDIT` or
`@generated`, and every `dest` in the adopter's own `[vendored]` table.

Exit codes (a state is never folded into a pass):

  0  pass, or the stage is not enabled (declared, not inferred)
  1  a count rose, a new file carries markers, a README is over budget without a
     baseline entry, or the baseline is missing / a mode was refused
  2  bad configuration, baseline or arguments -- fail loud
  3  NOT CONFIRMED: `git` unusable, a file is not UTF-8, or a fenced block or
     HTML comment never closes (it would hide every line below it). The gate
     fails on it.

Modes: `check` (default; what the gate runs), `--init` (write the first
baseline, refuses to overwrite), `--update-baseline` (lower or drop entries;
exits 1 and writes nothing while anything rose), `--update-baseline
--allow-additions` (the explicit flag that raises or adds -- shows in review).

Vendor-verbatim: copied byte-for-byte into adopters (manifest key
`docs_ratchet`), stdlib-only. Full procedure and limits: docs/docs-ratchet.md.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

REPO_ROOT = Path(__file__).resolve().parent.parent

BASELINE_VERSION = 1
DEFAULT_BASELINE = ".docs-ratchet-baseline.json"
DEFAULT_INCLUDE = ("README.md", "docs/")
DEFAULT_README_MAX_BYTES = 40960
README = "README.md"
#: Always excluded, whatever the adopter's own `exclude` adds.
BUILTIN_EXCLUDES = ("**/node_modules/**", "**/.venv/**", "**/venv/**")
GENERATED_MARKERS = ("DO NOT EDIT", "@generated")  # case-sensitive: "Do NOT edit this file per-app" is prose
GENERATED_HEAD_LINES = 5
GIT_TIMEOUT_S = 120

EXIT_PASS, EXIT_RISE, EXIT_CONFIG, EXIT_NOT_CONFIRMED = 0, 1, 2, 3

# Vendor-verbatim module: derives the flag locally (the shared `src/no_window.py`
# would not resolve in a consumer tree), the documented exception.
_NO_WINDOW = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0

_CONFIG_KEYS = {"enabled", "baseline", "include", "exclude", "readme_max_bytes", "allow_refs"}

_REF = re.compile(r"(?<![&#/])#(\d{1,5})(?![\w-])")
#: Whatever precedes a reference on its line and reads as its repo prefix (`owner/repo`).
_REF_PREFIX = re.compile(r"(?:[\w.-]+/)?[\w.-]*\Z")
_URL = re.compile(r"https?://[^\s<>]+")
_LINK_TARGET = re.compile(r"(?<=\])\([^)]*\)")
_REF_DEFINITION = re.compile(r"^([ \t>]*\[[^\]]*\]:[ \t]*)\S+")
_ATTRIBUTE_URL = re.compile(r"""\b(?:href|src)\s*=\s*(?:"[^"]*"|'[^']*')""", re.IGNORECASE)
_FENCE_OPEN = re.compile(r"^[ \t>]*(?:(?:[-+*]|\d{1,9}[.)])[ \t]+)*(`{3,}|~{3,})(.*)$")
_FENCE_CLOSE = re.compile(r"^[ \t>]*(`{3,}|~{3,})[ \t]*$")
_HTML_TOKEN = re.compile(r"`+|<!--|-->")
_HEADING = re.compile(r"^ {0,3}(?:> ?)*#{1,6}[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$")
_DATE = re.compile(r"(?<!\d)(?:19|20)\d\d-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01])(?!\d)")
_CHANGELOG = re.compile(
    r"^[\W_]*(?:\d+(?:\.\d+)*[.)]?\s+)?(?:changelog|change log|release notes|release history|what['’]s new)\b",
    re.IGNORECASE,
)


class ConfigError(RuntimeError):
    """The `[docs_ratchet]` table or the baseline file is unusable."""


class NotConfirmed(RuntimeError):
    """A file could not be scanned, so its count is unknown."""


@dataclass(frozen=True)
class Config:
    baseline: str
    include: tuple[str, ...]
    exclude: tuple[str, ...]
    readme_max_bytes: int
    allow_refs: tuple[str, ...]


@dataclass(frozen=True)
class Marker:
    line: int
    kind: str  # "ref", "dated-heading" or "changelog-heading"
    text: str  # what matched, plus the line it sits on, for messages


@dataclass(frozen=True)
class Entry:
    """One file's standing: its marker count, plus its size when it is an over-budget README."""

    markers: int
    size: int | None = None


@dataclass(frozen=True)
class Scan:
    markers: dict[str, list[Marker]]  # only files with at least one marker
    readme_size: int | None  # None when there is no in-scope README


# ----------------------------------------------------------------- config

def _str_list(table: dict[str, object], name: str, default: tuple[str, ...]) -> tuple[str, ...]:
    if name not in table:
        return default
    value = table[name]
    if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
        raise ConfigError(f"[docs_ratchet] {name} must be a list of non-empty strings")
    return tuple(value)


def parse_config(toml_text: str) -> Config | None:
    """`[docs_ratchet]` -> `Config`, or None when the stage is not enabled.

    An absent table, or `enabled = false`, is the one correct skip: the adopter
    declared it. Anything malformed raises `ConfigError` -- a typo'd key must not
    quietly run with defaults.
    """
    table = tomllib.loads(toml_text).get("docs_ratchet")
    if table is None:
        return None
    if not isinstance(table, dict):
        raise ConfigError("[docs_ratchet] must be a table")
    unknown = sorted(set(table) - _CONFIG_KEYS)
    if unknown:
        raise ConfigError(f"[docs_ratchet]: unknown key(s) {', '.join(unknown)}")
    enabled = table.get("enabled", False)
    if not isinstance(enabled, bool):
        raise ConfigError("[docs_ratchet] enabled must be true or false")
    if not enabled:
        return None
    baseline = table.get("baseline", DEFAULT_BASELINE)
    if not isinstance(baseline, str) or not baseline:
        raise ConfigError("[docs_ratchet] baseline must be a non-empty string")
    budget = table.get("readme_max_bytes", DEFAULT_README_MAX_BYTES)
    if isinstance(budget, bool) or not isinstance(budget, int) or budget < 1:
        raise ConfigError("[docs_ratchet] readme_max_bytes must be a positive integer")
    return Config(
        baseline,
        _str_list(table, "include", DEFAULT_INCLUDE),
        _str_list(table, "exclude", ()),
        budget,
        _str_list(table, "allow_refs", ()),
    )


def vendored_dests(toml_text: str) -> tuple[str, ...]:
    """Every `dest` in the adopter's own `[vendored]` table (files or folders)."""
    table = tomllib.loads(toml_text).get("vendored")
    if not isinstance(table, dict):
        return ()
    dests = []
    for entry in table.values():
        dest = entry.get("dest") if isinstance(entry, dict) else None
        if isinstance(dest, str) and dest.strip("/"):
            dests.append(dest.replace("\\", "/").strip("/"))
    return tuple(sorted(dests))


def load_config(root: Path) -> tuple[Config | None, tuple[str, ...]]:
    """(config or None when not enabled, vendored dests)."""
    path = root / ".fleet.toml"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"cannot read {path}: {exc}") from exc
    try:
        return parse_config(text), vendored_dests(text)
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path} is not valid TOML: {exc}") from exc


# ------------------------------------------------------------------- globs

def _glob_regex(glob: str) -> re.Pattern[str]:
    """Repo-root-anchored glob -> regex; `**/` is zero or more directories."""
    out: list[str] = []
    i = 0
    while i < len(glob):
        if glob.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif glob.startswith("**", i):
            out.append(".*")
            i += 2
        elif glob[i] == "*":
            out.append("[^/]*")
            i += 1
        elif glob[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(glob[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


def is_excluded(path: str, globs: tuple[str, ...]) -> bool:
    return any(_glob_regex(g).match(path) for g in globs)


def _under(path: str, prefix: str) -> bool:
    prefix = prefix.replace("\\", "/").strip("/")
    return path == prefix or path.startswith(prefix + "/")


def in_scope(path: str, cfg: Config, vendored: tuple[str, ...]) -> bool:
    """Is `path` a Markdown file this stage counts?"""
    if PurePosixPath(path).suffix.lower() != ".md":
        return False
    if not any(_under(path, p) for p in cfg.include):
        return False
    if any(_under(path, d) for d in vendored):
        return False
    return not is_excluded(path, BUILTIN_EXCLUDES + cfg.exclude)


def is_generated(text: str) -> bool:
    head = "\n".join(text.split("\n", GENERATED_HEAD_LINES)[:GENERATED_HEAD_LINES])
    return any(marker in head for marker in GENERATED_MARKERS)


# ---------------------------------------------------------------- counting

def _blank_html_comments(line: str, in_comment: bool) -> tuple[str, bool]:
    """Drop `<!-- -->` text from one line; return (rest, still inside a comment).

    A `<!--` inside an inline code span is code, not a comment opener, so backtick
    runs are tracked on the way (a run closes the span opened by one of equal length).
    """
    kept: list[str] = []
    pos = 0
    code_len: int | None = None
    for m in _HTML_TOKEN.finditer(line):
        tok = m.group()
        if in_comment:
            if tok == "-->":
                in_comment = False
                pos = m.end()
        elif tok[0] == "`":
            if code_len is None:
                code_len = len(tok)
            elif code_len == len(tok):
                code_len = None
        elif tok == "<!--" and code_len is None:
            kept.append(line[pos:m.start()])
            in_comment = True
    if not in_comment:
        kept.append(line[pos:])
    return "".join(kept), in_comment


def _blank_urls(line: str) -> str:
    """Remove every URL-shaped span so an anchor or issue link never counts."""
    line = _REF_DEFINITION.sub(lambda m: m.group(1), line)
    line = _ATTRIBUTE_URL.sub("", line)
    line = _LINK_TARGET.sub("()", line)
    return _URL.sub(" ", line)


def _written_ref(line: str, match: re.Match[str]) -> str:
    """The reference as the author wrote it, repo prefix included (`owner/repo#12`)."""
    prefix = _REF_PREFIX.search(line[:match.start()])
    return (prefix.group() if prefix else "") + match.group()


def _heading_marker(line: str, no: int) -> Marker | None:
    m = _HEADING.match(line)
    if not m:
        return None
    text = m.group(1)
    if _CHANGELOG.match(text):
        return Marker(no, "changelog-heading", f"{text.strip()}  | heading")
    date = _DATE.search(text)
    if date:
        return Marker(no, "dated-heading", f"{date.group()}  | {text.strip()}")
    return None


def scan_text(text: str, allow_refs: tuple[str, ...] = ()) -> list[Marker]:
    """Every history marker in one Markdown file's text; raises `NotConfirmed` on an unclosed block."""
    markers: list[Marker] = []
    fence: tuple[str, int, int] | None = None  # (fence char, run length, line it opened on)
    comment_opened: int | None = None
    for no, raw in enumerate(text.replace("\r\n", "\n").split("\n"), 1):
        if fence:
            close = _FENCE_CLOSE.match(raw)
            if close and close.group(1)[0] == fence[0] and len(close.group(1)) >= fence[1]:
                fence = None
            continue
        if comment_opened is None:
            opener = _FENCE_OPEN.match(raw)
            if opener and not (opener.group(1)[0] == "`" and "`" in opener.group(2)):
                fence = (opener.group(1)[0], len(opener.group(1)), no)
                continue
        line, inside = _blank_html_comments(raw, comment_opened is not None)
        if inside and comment_opened is None:
            comment_opened = no
        elif not inside:
            comment_opened = None
        line = _blank_urls(line)
        heading = _heading_marker(line, no)
        if heading:
            markers.append(heading)
        for ref in _REF.finditer(line):
            written = _written_ref(line, ref)
            if written not in allow_refs:
                markers.append(Marker(no, "ref", f"{written}  | {line.strip()}"))
    if fence:
        raise NotConfirmed(f"the fenced block opened on line {fence[2]} never closes")
    if comment_opened is not None:
        raise NotConfirmed(f"the HTML comment opened on line {comment_opened} never closes")
    return markers


# ------------------------------------------------------------------- files

def tracked_files(root: Path) -> list[str]:
    """Repo-relative, forward-slash paths of every tracked or untracked-but-not-ignored file."""
    env = dict(os.environ, GIT_OPTIONAL_LOCKS="0")  # a read-only sweep must not leave index locks
    try:
        proc = subprocess.run(
            ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=root, capture_output=True, env=env,
            stdin=subprocess.DEVNULL, creationflags=_NO_WINDOW, timeout=GIT_TIMEOUT_S, check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise NotConfirmed(f"git ls-files timed out after {GIT_TIMEOUT_S}s") from exc
    except OSError as exc:
        raise NotConfirmed(f"git could not start: {exc}") from exc
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
        raise NotConfirmed(f"git ls-files exited {proc.returncode}: {detail[-1] if detail else '(no output)'}")
    return sorted(p for p in proc.stdout.decode("utf-8", "replace").split("\0") if p)


def count_tree(root: Path, cfg: Config, vendored: tuple[str, ...]) -> Scan:
    """Markers per in-scope file, plus the root README's size in bytes."""
    found: dict[str, list[Marker]] = {}
    readme_size: int | None = None
    for path in tracked_files(root):
        if not in_scope(path, cfg, vendored):
            continue
        try:
            raw = (root / path).read_bytes()
        except FileNotFoundError:
            continue  # tracked but deleted in the working tree: nothing to count
        except OSError as exc:
            raise NotConfirmed(f"{path}: cannot be read: {exc}") from exc
        try:
            text = raw.decode("utf-8-sig")
        except UnicodeDecodeError as exc:
            raise NotConfirmed(f"{path}: is not valid UTF-8: {exc}") from exc
        if is_generated(text):
            continue
        if path == README:
            readme_size = len(raw.replace(b"\r\n", b"\n"))
        try:
            markers = scan_text(text, cfg.allow_refs)
        except NotConfirmed as exc:
            raise NotConfirmed(f"{path}: {exc}") from exc
        if markers:
            found[path] = markers
    return Scan(found, readme_size)


def current_entries(scan: Scan, cfg: Config) -> dict[str, Entry]:
    """What the baseline would record for this tree: files with markers, and an over-budget README."""
    entries = {path: Entry(len(found)) for path, found in scan.markers.items()}
    if scan.readme_size is not None and scan.readme_size > cfg.readme_max_bytes:
        entries[README] = Entry(entries.get(README, Entry(0)).markers, scan.readme_size)
    return entries


# ---------------------------------------------------------------- baseline

def read_baseline(path: Path) -> dict[str, Entry]:
    """Baseline file -> ``{path: Entry}``. Raises `ConfigError` on anything off."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise ConfigError(f"cannot read baseline {path}: {exc}") from exc
    except ValueError as exc:
        raise ConfigError(f"baseline {path} is not valid JSON: {exc}") from exc
    if not isinstance(data, dict) or data.get("version") != BASELINE_VERSION:
        raise ConfigError(f"baseline {path}: expected an object with version {BASELINE_VERSION}")
    raw_entries = data.get("entries")
    if not isinstance(raw_entries, list):
        raise ConfigError(f"baseline {path}: `entries` must be a list")
    out: dict[str, Entry] = {}
    for item in raw_entries:
        if not isinstance(item, dict) or not isinstance(item.get("key"), str):
            raise ConfigError(f"baseline {path}: malformed entry {item!r}")
        markers, size = item.get("markers"), item.get("bytes")
        if isinstance(markers, bool) or not isinstance(markers, int) or markers < 0:
            raise ConfigError(f"baseline {path}: malformed entry {item!r}")
        if size is not None and (isinstance(size, bool) or not isinstance(size, int) or size < 1):
            raise ConfigError(f"baseline {path}: malformed entry {item!r}")
        if markers == 0 and size is None:
            raise ConfigError(f"baseline {path}: entry {item!r} records nothing")
        out[item["key"]] = Entry(markers, size)
    return out


def render_baseline(entries: dict[str, Entry]) -> str:
    """Sorted, one entry per line, no line numbers, so a baseline diff reviews cleanly."""
    lines = []
    for key in sorted(entries):
        entry = entries[key]
        record: dict[str, object] = {"key": key, "markers": entry.markers}
        if entry.size is not None:
            record["bytes"] = entry.size
        lines.append("    " + json.dumps(record, ensure_ascii=False))
    body = "[\n" + ",\n".join(lines) + "\n  ]" if lines else "[]"
    return f'{{\n  "version": {BASELINE_VERSION},\n  "entries": {body}\n}}\n'


def diff(current: dict[str, Entry], baseline: dict[str, Entry]) -> tuple[list[str], list[str]]:
    """(files that rose or are new, files that fell or are gone), sorted."""
    none = Entry(0)
    rose, shrank = [], []
    for path in sorted(set(current) | set(baseline)):
        cur, base = current.get(path, none), baseline.get(path, none)
        if cur.markers > base.markers or (cur.size is not None and (base.size is None or cur.size > base.size)):
            rose.append(path)
        if cur.markers < base.markers or (
            base.size is not None and (cur.size is None or cur.size < base.size)
        ):
            shrank.append(path)
    return rose, shrank


# -------------------------------------------------------------------- CLI

def _total(entries: dict[str, Entry]) -> int:
    return sum(e.markers for e in entries.values())


def _report_rose(
    rose: list[str], scan: Scan, current: dict[str, Entry], baseline: dict[str, Entry], budget: int
) -> None:
    print(f"docs ratchet: {len(rose)} file(s) above the baseline:")
    for path in rose:
        cur, base = current[path], baseline.get(path)
        if cur.size is not None and (base is None or base.size is None or cur.size > base.size):
            was = f"baseline {base.size:,} bytes" if base and base.size is not None else "not baselined"
            print(f"  {path}: {cur.size:,} bytes, over the {budget:,}-byte budget ({was})")
        if cur.markers > (base.markers if base else 0):
            print(f"  {path}: {cur.markers} history marker(s) (baseline {base.markers if base else 'none -- not baselined'})")
            for marker in scan.markers.get(path, []):
                print(f"      line {marker.line}: {marker.kind}: {marker.text}")


def run(root: Path, *, init: bool, update: bool, allow_additions: bool) -> int:
    try:
        cfg, vendored = load_config(root)
    except ConfigError as exc:
        print(f"docs ratchet: CONFIG ERROR: {exc}")
        return EXIT_CONFIG
    if cfg is None:
        if init or update:
            print("docs ratchet: not enabled -- set [docs_ratchet] enabled = true in .fleet.toml first")
            return EXIT_CONFIG
        print("docs ratchet: not enabled (no [docs_ratchet] enabled = true in .fleet.toml)")
        return EXIT_PASS
    baseline_path = root / cfg.baseline

    baseline: dict[str, Entry] = {}
    if init:
        if baseline_path.exists():
            print(f"docs ratchet: {cfg.baseline} already exists; --init never overwrites it")
            return EXIT_CONFIG
    elif baseline_path.is_file():
        try:
            baseline = read_baseline(baseline_path)
        except ConfigError as exc:
            print(f"docs ratchet: BASELINE ERROR: {exc}")
            return EXIT_CONFIG
    else:
        print(f"docs ratchet: FAIL: baseline {cfg.baseline} is missing -- run `python scripts/docs_ratchet.py --init`")
        return EXIT_RISE

    try:
        scan = count_tree(root, cfg, vendored)
    except NotConfirmed as exc:
        print(f"docs ratchet: NOT CONFIRMED: {exc}")
        print("  (the count could not be established, so it is neither a pass nor a clean tree)")
        return EXIT_NOT_CONFIRMED
    current = current_entries(scan, cfg)

    if init:
        baseline_path.write_text(render_baseline(current), encoding="utf-8", newline="\n")
        print(f"docs ratchet: wrote {cfg.baseline} with {len(current)} file(s), {_total(current)} marker(s)")
        return EXIT_PASS

    rose, shrank = diff(current, baseline)
    if update:
        if rose and not allow_additions:
            _report_rose(rose, scan, current, baseline, cfg.readme_max_bytes)
            print("docs ratchet: nothing written -- remove the markers or shrink the README, "
                  "or raise the baseline with --allow-additions")
            return EXIT_RISE
        baseline_path.write_text(render_baseline(current), encoding="utf-8", newline="\n")
        print(f"docs ratchet: {cfg.baseline} now has {len(current)} file(s), {_total(current)} marker(s) "
              f"({len(shrank)} lowered or dropped, {len(rose)} raised or added)")
        return EXIT_PASS

    if rose:
        _report_rose(rose, scan, current, baseline, cfg.readme_max_bytes)
        print("  A doc states what is true and why, in the present tense; how it got here belongs in git, the PR "
              "and the issue (docs/readme-and-docs.md). Reword it, or move the detail to docs/<topic>.md for a "
              "README; or (reviewed) raise the baseline with `--update-baseline --allow-additions`.")
        return EXIT_RISE
    readme = f"; README {scan.readme_size:,} of {cfg.readme_max_bytes:,} bytes" if scan.readme_size is not None else ""
    print(f"docs ratchet: PASS ({_total(current)} marker(s) in {len(scan.markers)} file(s), none above the baseline{readme})")
    if shrank:
        print(f"  {len(shrank)} file(s) are below the baseline -- run "
              f"`python scripts/docs_ratchet.py --update-baseline` to lower it")
    return EXIT_PASS


